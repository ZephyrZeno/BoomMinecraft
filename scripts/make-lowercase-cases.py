"""Build-only case inputs; expected values come independently from the JVM."""
import json, random, re, sys
from pathlib import Path
cases={}
def add(language,units):
    line=language+' '+('null' if units is None else ','.join(format(v,'x') for v in units) if units else '-')
    cases[line]=None
def units(cp):
    if cp<0x10000:return [cp]
    cp-=0x10000;return [0xd800+(cp>>10),0xdc00+(cp&1023)]
text=Path('native/runtime/unicode_case.asm').read_text()
for cp,_,_ in re.findall(r'DWORD 0([0-9A-Fa-f]+)h, 0([0-9A-Fa-f]+)h, 0([0-9A-Fa-f]+)h',text):
    for language in ('-','tr','az','lt'):add(language,units(int(cp,16)))
special=[[],[0],[0xffff],[0xd800],[0xdc00],[0xdbff,0xdfff],[0xd83d,0xde00],
 [0x49],[0x130],[0x49,0x307],[0x49,0x307,0x307],[0x49,0x323,0x307],
 [0x49,0x301,0x307],[0x49,0x323,0x301],[0x4a,0x301],[0x12e,0x301],
 [0xcc],[0xcd],[0x128],[0x130,0x307],[0x49,0x345,0x307],
 [0x3a3],[0x41,0x3a3],[0x41,0x3a3,0x42],[0x41,0x301,0x3a3],
 [0x41,0x27,0x3a3],[0x41,0x3a3,0x27,0x42],[0x41,0xffff,0x3a3],
 [0x41,0x3a3,0xaa],[0x41,0x3a3,0x345],[0x41,0x3a3,0x2b0],
 [0x4e2d,0x41,0x3a3],[0xe01,0xe32,0x41,0x3a3],
 [0x41,0x3a3,0x20,0x49,0x130,0xd83d,0xde00],
 [0x27,0x301,0x130,0x3c3,0x49,0xae5b,0xd800,0xdc00,0x3a3,0x307]]
for language in ('-','tr','az','lt','en','de','zh','ja','th','null'):
    add(language,None)
    for text in special:
        if language!='th' or 0x3a3 not in text:add(language,text)
rng=random.Random(62062)
interesting=[0x41,0x61,0x49,0x4a,0x130,0x12e,0x307,0x301,0x323,0x345,0x3a3,0x3c3,0x27,0x20,0xffff,0xd800,0xdc00]
for i in range(2048):
    language=('-','tr','az','lt','en','zh')[i%6]
    text=[rng.choice(interesting) if rng.randrange(3) else rng.randrange(65536) for _ in range(rng.randrange(33))]
    add(language,text)
Path(sys.argv[1]).write_text('\n'.join(cases)+'\n')
print(json.dumps(dict(unique_cases=len(cases),mapping_rows=2879,expected_values_are_not_generated=True)))
